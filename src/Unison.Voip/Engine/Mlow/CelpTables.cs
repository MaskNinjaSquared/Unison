        /// <summary>Integer, bit-exact dcmf-&gt;cmf (truncating-int normalize); cmf has dcmfLen+1 entries.</summary>
        public static void CelpDcmfToCmf(byte[] dcmf, int dcmfOffset, int dcmfLen, ushort[] cmf)
        {
            int sum = 0;
            for (int n = 0; n < dcmfLen; n++)
            {
                int tmp = dcmf[dcmfOffset + n] + 1;
                tmp *= tmp;
                if (tmp > 65535)
                {
                    tmp = 65535;
                }

                cmf[n + 1] = (ushort)tmp;
                sum += tmp;
            }

            cmf[0] = 0;
            for (int n = 1; n < dcmfLen + 1; n++)
            {
                cmf[n] = unchecked((ushort)(cmf[n - 1] + (ushort)((cmf[n] * (32767 - dcmfLen)) / sum) + 1));
            }
        }
